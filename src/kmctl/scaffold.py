"""Set a repository up with docs/, an OKF bundle and an agent-file block.

It never touches a file that exists, with four exceptions: the kmctl block
in CLAUDE.md and AGENTS.md, the first decision's index entry and log line
(ADR 0011), the root index entry and log line of a manifesto or summary it
writes into a kept bundle (ADR 0027), and a docs/ folder index kmctl
generated (ADR 0022). The knowledge rules come with kmctl's APM package, which
APM installs (ADR 0014, ADR 0020).
"""

import os
import re
from dataclasses import dataclass
from dataclasses import field as dataclass_field
from datetime import UTC, datetime
from importlib.metadata import version
from pathlib import Path

from kmctl.concepts import append_log, new_concept
from kmctl.docs_index import fix_folder_indexes
from kmctl.doctor import harnesses_found
from kmctl.kinds import skeleton

OKF_VERSION = "0.2"

AGENT_FILES = ("CLAUDE.md", "AGENTS.md")
BLOCK_START, BLOCK_END = "<!-- kmctl:start -->", "<!-- kmctl:end -->"
#: The whole of a CLAUDE.md init writes beside an AGENTS.md: Claude Code reads
#: AGENTS.md only through it, once (ADR 0011).
AGENTS_IMPORT = "@AGENTS.md\n"

#: Where each harness loads rules from, with the tool's name, for the block.
RULES_FOLDERS = {
    "claude": "`.claude/rules/` (Claude Code)",
    "antigravity": "`.agents/rules/` (Antigravity)",
    "opencode": "`.opencode/rules/` (OpenCode)",
}
#: Where ``block`` names the rules folders in ``BLOCK``.
RULES_MARK = "{rules}"

BLOCK = f"""{BLOCK_START}
## Project knowledge (kmctl)

| What you need | Where it lives |
|---|---|
| How to use the project | `docs/`, one folder per Diataxis type; each folder's `README.md` lists its pages and is generated by `kmctl check --fix`, and `docs/README.md` links the folders |
| What the knowledge says as a whole | `.okf/summary.md` |
| What the project is for, its invariants and values | `.okf/manifesto.md` |
| Why a choice was made | `.okf/decisions/`, one record per choice with the alternative it rejected |
| The design as diagrams | `.okf/architecture/`, each page with a Depicts section naming the files it covers |
| Lessons, designs not built, spikes, handoffs | `.okf/practices/`, `.okf/proposals/`, `.okf/prototypes/`, `.okf/handoffs/` |

Start at `.okf/summary.md`, which links down to the rest. The rules for writing knowledge are in {RULES_MARK}.

Your duties while you work:

1. Record each choice as a decision when you make it: `kmctl new decision 'Title' --description 'One sentence.'`, then write its Context, Decision (with the alternative you rejected) and Consequences.
2. When a concept describes code, name that code with `--source PATH` (repeat it for more) so `kmctl review due` lists the concept once the code changes; give anything time-bound a `--stale-after` (`30d`, `6m`, or a date like `2027-01-15`).
3. Keep `.okf/architecture/` matching the code: add or update a page when the design changes.
4. A `docs/` page may carry `description`, `stale_after` and `sources` front matter; `kmctl new doc` writes them. Never edit a folder `README.md` index: run `kmctl check --fix`.
5. When you add or change a concept, update `.okf/summary.md`, which distils what the knowledge says as a whole in 500 words at most, citing concepts as evidence (the indexes list the concepts), or run `kmctl summary ack` when it is still right.
6. Run `kmctl check` before you finish.
{BLOCK_END}
"""

#: The manifesto's root index entry text.
MANIFESTO_LINE = "what this project is for, its invariants and values."
#: The summary's description and index entry text.
SUMMARY_LINE = (
    "The whole project in at most 500 words: what the knowledge says, "
    "citing the concepts; start here."
)
#: The line init writes under each of the summary's sections: what goes there.
#: Each section distils; the indexes list the concepts.
SUMMARY_PROMPTS = {
    "The project": "What the project is for and who uses it, in a few sentences.",
    "How it works": (
        "The design as a whole: the parts, how they fit and the main flows, "
        "citing the architecture pages."
    ),
    "What it has settled": (
        "The principles and constraints the decisions and practices set, with "
        "their reasons, grouped by idea and citing the records inline as "
        "evidence; never one bullet per decision."
    ),
    "Where it stands": (
        "What works, what is open or in flight, and what the bundle does not cover yet."
    ),
}

FIRST_DECISION = "Keep project knowledge in an OKF bundle"
FIRST_DESCRIPTION = (
    "Project knowledge lives in an OKF bundle in .okf/, next to the code, "
    "not in a wiki or README notes."
)
FIRST_BODY = """## Context

This repository needs a place for knowledge that people and agents working on
it can find and trust: what the project is for, why each choice was made, and
how the design fits together. Knowledge kept in someone's head or in chat is
lost when they move on, and an agent starting a session cannot read it.

## Decision

Keep project knowledge in an OKF bundle in `.okf/`, set up and checked by
kmctl, next to the code it describes. Each choice gets a decision record when
it is made, the design gets diagrams in `.okf/architecture/`, and `docs/`
holds pages for people who use the project.

Rejected:

- A wiki. It lives apart from the code, so it drifts, and an agent cannot read
  it in a session.
- README-only notes. One file mixes what users and maintainers need and loses
  the why of each choice.
- Nothing. Every new session and every new person finds the same reasons
  again, or acts without them.

## Consequences

- Each change that makes a choice also writes a decision record, and a change
  to the design updates its architecture page.
- `kmctl check` keeps the indexes and links in step, so a reader can trust
  them.
- A record costs a few minutes per choice and saves rereading the code to
  find out why.
"""


@dataclass
class ScaffoldResult:
    """What ``scaffold`` wrote, what it left alone, and what the user must finish by hand.

    Paths are relative to the root. ``scaffold`` never edits a kept file, with
    four exceptions, all listed in ``updated``: it adds or replaces the kmctl
    block in CLAUDE.md and AGENTS.md, when it writes the first decision into a
    kept bundle with no decision record it adds its index entry and log line,
    when it writes a manifesto or summary into a kept bundle it adds its root
    index entry and log line (the page is then listed in ``linked``), and it
    rewrites a docs/ folder index kmctl generated. A new CLAUDE.md
    beside an AGENTS.md holds only ``@AGENTS.md`` and is listed in
    ``created``. A warning names a kept index or log that is not UTF-8, so
    ``scaffold`` could not add a new page to it, and a CLAUDE.md or AGENTS.md symlink left alone
    because it is dangling or points outside the repository.
    """

    created: list[str] = dataclass_field(default_factory=list)
    skipped: list[str] = dataclass_field(default_factory=list)
    updated: list[str] = dataclass_field(default_factory=list)
    warnings: list[str] = dataclass_field(default_factory=list)
    linked: list[str] = dataclass_field(default_factory=list)


def _files(now: datetime) -> dict[str, str]:
    at = now.strftime("%Y-%m-%dT%H:%M:%SZ")
    by = f"process:kmctl/{version('kmctl')}"
    return {
        "docs/README.md": (
            "# Documentation\n\n"
            "Pages for people who use this project, one folder per Diataxis type\n"
            "(tutorials, how-to, reference, explanation). Each folder is linked\n"
            "here, and its README.md, which kmctl check --fix writes, lists its pages.\n"
        ),
        ".okf/index.md": (
            f'---\nokf_version: "{OKF_VERSION}"\n---\n\n'
            "# Knowledge bundle\n\n"
            "For agents and people working on this repository.\n\n"
            f"- [Summary](summary.md): {SUMMARY_LINE}\n"
            f"- [Manifesto](manifesto.md): {MANIFESTO_LINE}\n"
        ),
        ".okf/log.md": (
            f"# Log\n\n## {now.date().isoformat()}\n\n"
            "- Created the bundle with `kmctl init`: `manifesto`, `summary`.\n"
        ),
        ".okf/manifesto.md": (
            "---\n"
            "type: manifesto\n"
            'title: "Manifesto"\n'
            'description: "What this project is for, where its parts live, its invariants and its values."\n'
            "generated:\n"
            f"  by: {by}\n"
            f"  at: {at}\n"
            "tags: [manifesto]\n"
            "---\n\n"
            "# Manifesto\n\n"
            + "\n\n".join(f"## {h}" for h in skeleton("manifesto"))
            + "\n"
        ),
        ".okf/summary.md": (
            "---\n"
            "type: summary\n"
            'title: "Summary"\n'
            f'description: "{SUMMARY_LINE}"\n'
            "generated:\n"
            f"  by: {by}\n"
            f"  at: {at}\n"
            "tags: [summary]\n"
            "---\n\n"
            "# Summary\n\n"
            + "\n\n".join(
                f"## {h}\n\n{SUMMARY_PROMPTS[h]}" for h in skeleton("summary")
            )
            + "\n"
        ),
    }


def _text(path: Path) -> str | None:
    """The UTF-8 text of ``path``, or None when it is not UTF-8."""
    try:
        return path.read_text(encoding="utf-8")
    except UnicodeDecodeError:
        return None


def block(harnesses: list[str]) -> str:
    """The kmctl block, naming the rules folder of each harness in ``harnesses``, or of all three when it is empty."""
    folders = [RULES_FOLDERS[h] for h in harnesses or RULES_FOLDERS]
    rules = ", ".join(folders[:-1]) + " and " if len(folders) > 1 else ""
    return BLOCK.replace(RULES_MARK, rules + folders[-1])


def _with_block(text: str, new: str) -> str | None:
    """``text`` with the kmctl block replaced by or appended as ``new``, or None when its markers are broken."""
    start, end = text.find(BLOCK_START), text.find(BLOCK_END)
    if start == -1 and end == -1:
        return text.rstrip("\n") + "\n\n" + new if text.strip() else new
    if start == -1 or end < start or text.count(BLOCK_START) > 1:
        return None
    return text[:start] + new.rstrip("\n") + text[end + len(BLOCK_END) :]


def _unsafe_link(root: Path, path: Path) -> str | None:
    """Why ``path`` is a symlink init must not write through, or None when it is safe."""
    if not path.is_symlink():
        return None
    if not path.exists():
        why = "which is missing"
    elif not path.resolve().is_relative_to(root.resolve()):
        why = "outside the repository"
    else:
        return None
    return f"{path.name} is a symlink to {os.readlink(path)}, {why}"


def _imports_agents(text: str | None) -> bool:
    return text is not None and any(
        line.strip() == AGENTS_IMPORT.strip() for line in text.splitlines()
    )


def _write_block(root: Path, result: ScaffoldResult) -> None:
    """Add the kmctl block to each CLAUDE.md and AGENTS.md once per real file, or write CLAUDE.md.

    A symlink inside the repository is written through in place, so
    CLAUDE.md -> AGENTS.md stays a link and its target gets one block. A
    symlink that is dangling or resolves outside the repository is left alone
    with a warning. A CLAUDE.md with an ``@AGENTS.md`` line, beside an
    AGENTS.md, gets no block, since it loads AGENTS.md's. When CLAUDE.md is
    missing, init writes it as ``@AGENTS.md`` beside an AGENTS.md, or with
    the block when neither file exists; beside an unsafe AGENTS.md link it
    writes no CLAUDE.md. An AGENTS.md that is not a file (a folder, say)
    counts as absent, with a warning.
    """
    claude, agents = root / "CLAUDE.md", root / "AGENTS.md"
    kmctl_block = block(harnesses_found(root))
    has_agents = os.path.lexists(agents)
    unsafe_agents = _unsafe_link(root, agents) if has_agents else None
    # An AGENTS.md that is a folder or another non-file loads nothing, so it
    # counts as absent for the import, with a warning.
    odd_agents = has_agents and unsafe_agents is None and not agents.is_file()
    if odd_agents:
        result.warnings.append(
            "AGENTS.md is not a file, so kmctl treated it as absent: the kmctl "
            "block goes in CLAUDE.md instead"
        )
        has_agents = False
    seen: set[Path] = set()
    for rel in AGENT_FILES:
        path = root / rel
        if not os.path.lexists(path):
            continue
        unsafe = _unsafe_link(root, path)
        if unsafe is not None:
            if rel == "AGENTS.md" and not os.path.lexists(claude):
                unsafe += (
                    ", so kmctl wrote no CLAUDE.md: one with the block would hide "
                    "AGENTS.md from Claude Code, and one importing it would load no block"
                )
            else:
                unsafe += ", so kmctl left it alone"
            result.warnings.append(f"{unsafe}; fix the link, then run kmctl init again")
            result.skipped.append(rel)
            continue
        if not path.is_file():
            continue
        real = path.resolve()
        if real in seen:
            continue
        text = _text(real)
        if rel == "CLAUDE.md" and has_agents and _imports_agents(text):
            result.skipped.append(rel)
            continue
        seen.add(real)
        new = _with_block(text, kmctl_block) if text is not None else None
        if new is None:
            why = "is not UTF-8 text" if text is None else _marker_problem(text)
            result.warnings.append(
                f"the kept {rel} {why}, so kmctl left it without its block; "
                "fix it by hand, then run kmctl init again"
            )
            result.skipped.append(rel)
        elif new == text:
            result.skipped.append(rel)
        else:
            real.write_text(new, encoding="utf-8")
            result.updated.append(rel)
    if os.path.lexists(claude) or unsafe_agents is not None:
        return
    claude.write_text(AGENTS_IMPORT if has_agents else kmctl_block, encoding="utf-8")
    result.created.append("CLAUDE.md")


def _marker_problem(text: str) -> str:
    """Say what is wrong with a file's kmctl markers, for the warning."""
    starts, ends = text.count(BLOCK_START), text.count(BLOCK_END)
    if starts > 1 or ends > 1:
        return f"has {starts} {BLOCK_START} and {ends} {BLOCK_END} markers, not one of each"
    if starts == 0:
        return f"has {BLOCK_END} with no {BLOCK_START} before it"
    return f"has {BLOCK_START} without a {BLOCK_END} after it"


#: A markdown list item whose text starts with a link: an index entry.
_ENTRY_LINE = re.compile(r"\s*[-*+]\s+\[")


def _insert_entry(text: str, entry: str, after: str | None) -> str:
    """``text``, a root index, with the line ``entry`` added in its place.

    It goes right after the entry linking ``after`` and any lines that
    entry wraps onto; with no such entry, before the first entry; with no
    entries at all, at the end. No other line changes.
    """
    lines = text.splitlines(keepends=True)
    entries = [i for i, line in enumerate(lines) if _ENTRY_LINE.match(line)]
    at = entries[0] if entries else len(lines)
    linked = [i for i in entries if after is not None and f"]({after})" in lines[i]]
    if linked:
        at = linked[0] + 1
        while (
            at < len(lines)
            and lines[at].strip()
            and lines[at][0] in " \t"
            and at not in entries
        ):
            at += 1
    if at == len(lines) and lines and not lines[-1].endswith("\n"):
        lines[-1] += "\n"
    return "".join([*lines[:at], entry + "\n", *lines[at:]])


def _link_new_pages(root: Path, now: datetime, result: ScaffoldResult) -> None:
    """Link a manifesto or summary init just wrote from a kept root index, and log it.

    In a bundle that existed before, the kept .okf/index.md does not list the
    new page, so ``kmctl check`` would fail. Each new page gets its one entry
    in the index, in the order a fresh index has (summary, then manifesto),
    and a line in .okf/log.md, unless they are there already. Nothing else in
    either file changes. A kept file that is not UTF-8 is left alone with a
    warning.
    """
    okf = root / ".okf"
    pages = (
        ("summary", f"- [Summary](summary.md): {SUMMARY_LINE}", None),
        ("manifesto", f"- [Manifesto](manifesto.md): {MANIFESTO_LINE}", "summary.md"),
    )
    for name, entry, after in pages:
        rel = f".okf/{name}.md"
        if rel not in result.created:
            continue
        for kept, path in (
            (".okf/index.md", okf / "index.md"),
            (".okf/log.md", okf / "log.md"),
        ):
            if kept not in result.skipped and kept not in result.updated:
                continue  # init wrote it just now, with the page in it
            text = _text(path)
            if text is None:
                result.warnings.append(
                    f"the kept {kept} is not UTF-8 text, so kmctl could not add "
                    f"the new {name} to it; add it by hand"
                )
                continue
            if kept == ".okf/index.md":
                if f"]({name}.md)" in text:
                    continue
                path.write_text(_insert_entry(text, entry, after), encoding="utf-8")
                if rel not in result.linked:
                    result.linked.append(rel)
            elif f"`{name}`" in text:
                continue
            else:
                append_log(path, f"- Added `{name}` with `kmctl init`.", now)
            if kept in result.skipped:
                result.skipped.remove(kept)
                result.updated.append(kept)
    result.linked.sort()


def _write_first_decision(root: Path, now: datetime, result: ScaffoldResult) -> None:
    """Record the first decision through ``kmctl new decision``'s writer, then fill its sections.

    It writes nothing when .okf/decisions/ or a folder in it holds any
    ``*.md`` file other than ``index.md``, whatever its title and even when
    its front matter does not parse.
    """
    okf = root / ".okf"
    decisions = okf / "decisions"
    if any(p.name != "index.md" for p in decisions.rglob("*.md")):
        return
    unreadable = [
        p.relative_to(root).as_posix()
        for p in (okf / "index.md", okf / "log.md", decisions / "index.md")
        if p.is_file() and _text(p) is None
    ]
    if unreadable:
        result.warnings.append(
            f"kmctl did not record the decision {FIRST_DECISION!r} because "
            f"the kept {', '.join(unreadable)} is not UTF-8 text; fix it, then "
            "run kmctl init again"
        )
        return
    shared = (".okf/index.md", ".okf/log.md", ".okf/decisions/index.md")
    before = {rel: _text(root / rel) for rel in shared if (root / rel).is_file()}
    made = new_concept(root, "decision", FIRST_DECISION, FIRST_DESCRIPTION, now)
    path = root / made.path
    log = root / ".okf" / "log.md"
    cid = Path(made.path).relative_to(".okf").with_suffix("").as_posix()
    log.write_text(
        log.read_text(encoding="utf-8").replace(
            f"- Added `{cid}` with `kmctl new decision`.",
            f"- Added `{cid}` with `kmctl init`.",
        ),
        encoding="utf-8",
    )
    for rel, text in before.items():
        if (
            _text(root / rel) != text
            and rel not in result.created
            and rel not in result.updated
        ):
            if rel in result.skipped:
                result.skipped.remove(rel)
            result.updated.append(rel)
    head = path.read_text(encoding="utf-8").split("\n## Context", 1)[0]
    path.write_text(head.rstrip("\n") + "\n\n" + FIRST_BODY, encoding="utf-8")
    if made.created_section:
        result.created.append(".okf/decisions/index.md")
    result.created.append(made.path)


def scaffold(root: Path, now: datetime | None = None) -> ScaffoldResult:
    """Set ``root`` up: docs/, a starter .okf/ bundle, the agent-file block, a first decision.

    It writes docs/README.md and .okf/index.md, log.md, manifesto.md and
    summary.md; the kmctl block in each CLAUDE.md and AGENTS.md; a new CLAUDE.md when there is
    none, holding only ``@AGENTS.md`` beside an AGENTS.md and the block
    otherwise; and the decision "Keep project knowledge in an OKF bundle" when
    .okf/decisions/ holds no decision record. It writes no rules: those come
    with kmctl's APM package. A file that exists is kept, except for the kmctl block, the
    first decision's index entry and log line, and the root index entry and
    log line of a manifesto or summary it writes into a kept bundle, so
    ``kmctl check`` passes after it. Each docs/ Diataxis folder's
    README.md index is written when missing, or rewritten when kmctl
    generated it and it is out of date. A CLAUDE.md that imports
    ``@AGENTS.md`` gets no block. The block names the rules folder of each
    harness ``harnesses_found`` reports, or all three when it finds none.
    A CLAUDE.md or AGENTS.md symlink that is dangling or points outside the
    repository is left alone with a warning; when AGENTS.md is such a link and
    there is no CLAUDE.md, no CLAUDE.md is written.

    Parameters
    ----------
    root : Path
        The repository to set up.
    now : datetime | None
        The time written into the bundle; the current UTC time when omitted.

    Returns
    -------
    ScaffoldResult
        The files created, the files that already existed and were kept, the
        kept files it changed (an agent file's kmctl block, the first
        decision's index entry and log line, a new page's root index entry
        and log line, or a generated docs/ folder index), the new pages it
        linked from a kept root index, and a warning for each kept file
        kmctl could not finish.
    """
    result = ScaffoldResult()
    now = now or datetime.now(UTC)
    for rel, text in _files(now).items():
        path = root / rel
        if path.exists():
            result.skipped.append(rel)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        result.created.append(rel)
    _link_new_pages(root, now, result)
    created, updated = fix_folder_indexes(root)
    result.created += created
    result.updated += updated
    _write_block(root, result)
    _write_first_decision(root, now, result)
    return result
