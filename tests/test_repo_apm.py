"""This repository installs its upstream rules and skills with APM.

apm.yml lists them, pinned to one jasperhg90/skills commit, and apm.lock.yaml
records what `apm install` resolved. These tests read those files and the
installed rules; they make no network calls.
"""

import hashlib
import re
import subprocess
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]

#: The jasperhg90/skills commit every apm.yml entry is pinned to. It must be
#: the commit that merges https://github.com/JasperHG90/skills/pull/139, which
#: adds this repository's Test tiers text to python-testing. To repin: change
#: it here and in apm.yml, then rerun `apm install`.
PINNED = "7a5e072ae8aad76caa9c13645317347c64cce729"

SOURCE = "jasperhg90/skills"

RULES = {
    "async-python",
    "dependency-choice",
    "httpx-for-http",
    "interface-audience",
    "plain-language",
    "pre-existing-issues",
    "prompts-may-code-must",
    "pydantic-boundaries",
    "python-docstrings",
    "python-testing",
    "python-type-hints",
    "uv-installer",
    "prek-code-quality",
}

SKILLS = {"agent-creator", "rule-creator", "generate-art"}

#: sha256 of the AGENTS.md guidelines text as it stood between its old markers.
GUIDELINES_SHA256 = "a16a4f36531df0ecc8b4f64b6d1dcf04148dcf181bbe794ac4254faec6fb2984"


def _manifest() -> dict:
    return yaml.safe_load((ROOT / "apm.yml").read_text())


def _entries() -> list[str]:
    return _manifest()["dependencies"]["apm"]


def _split(entry: str) -> tuple[str, str]:
    path, _, ref = entry.partition("#")
    return path, ref


def test_manifest_lists_every_rule_and_skill() -> None:
    paths = {_split(e)[0] for e in _entries()}
    want = {f"{SOURCE}/rules/{r}.instructions.md" for r in RULES} | {
        f"{SOURCE}/skills/tools/{s}" for s in SKILLS
    }
    assert paths == want


def test_manifest_pins_every_entry() -> None:
    unpinned = [e for e in _entries() if _split(e)[1] != PINNED]
    assert not unpinned, f"entries not pinned to {PINNED}: {unpinned}"


def test_manifest_targets_claude() -> None:
    assert _manifest()["targets"] == ["claude"]


def test_manifest_lock_pins_commit_and_hashes() -> None:
    lock = yaml.safe_load((ROOT / "apm.lock.yaml").read_text())
    deps = lock["dependencies"]
    assert len(deps) == len(RULES) + len(SKILLS)
    for dep in deps:
        assert dep["resolved_commit"] == PINNED, dep
        hashes = dep.get("deployed_file_hashes") or {}
        assert hashes, f"{dep.get('virtual_path')} has no file hashes"
        assert all(re.fullmatch(r"sha256:[0-9a-f]{64}", h) for h in hashes.values())


def test_no_aim_files() -> None:
    assert not (ROOT / "aim.toml").exists()
    assert not (ROOT / "aim.lock.toml").exists()


def test_no_aim_in_agents_md() -> None:
    text = (ROOT / "AGENTS.md").read_text()
    assert "aim:" not in text
    assert "auto-generated by" not in text


def test_no_aim_guidelines_text_unchanged() -> None:
    """The guidelines block, once a marker region, keeps its text."""
    text = (ROOT / "AGENTS.md").read_text()
    start = text.index("Behavioral guidelines to reduce common LLM coding mistakes.")
    end = text.index("rather than after mistakes.\n", start) + len(
        "rather than after mistakes.\n"
    )
    digest = hashlib.sha256(text[start:end].encode()).hexdigest()
    assert digest == GUIDELINES_SHA256


def test_no_aim_named_in_tracked_files() -> None:
    """No tracked file outside .loop/ names aim as the manager of its files."""
    listed = subprocess.run(
        ["git", "ls-files"], cwd=ROOT, capture_output=True, text=True, check=True
    ).stdout.split()
    this = Path(__file__).relative_to(ROOT).as_posix()
    pattern = re.compile(
        r"agent-integrations-manager|aim\.(lock\.)?toml|aim-managed|\baim:|by aim\b",
        re.IGNORECASE,
    )
    found = []
    for name in listed:
        path = ROOT / name
        if name.startswith(".loop/") or name == this or not path.is_file():
            continue
        try:
            text = path.read_text()
        except UnicodeDecodeError:
            continue
        found += [f"{name}: {m.group(0)}" for m in pattern.finditer(text)]
    assert not found, found


def test_python_testing_kept_tiers() -> None:
    text = (ROOT / ".claude" / "rules" / "python-testing.md").read_text()
    assert re.search(r"^## Test tiers", text, re.MULTILINE)
    for name in (
        "measure-before-marking",
        "run-your-own-test",
        "every-tier-runs-somewhere",
    ):
        assert f'<constraint name="{name}">' in text, name


def test_rules_managed_from_apm() -> None:
    text = (ROOT / "tests" / "test_rules.py").read_text()
    assert "apm.yml" in text
    assert not re.search(r"\baim\b", text, re.IGNORECASE)
    pyproject = (ROOT / "pyproject.toml").read_text()
    assert not re.search(r"\baim\b", pyproject, re.IGNORECASE)
